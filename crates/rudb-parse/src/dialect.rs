//! SQL parser dialects installed in this build.
//!
//! The registry has one entry today because the vendored grammar is DuckDB's grammar. Keeping the
//! name here rather than in the settings layer makes `current_dialect` a lookup whose behavior
//! changes when another parser is registered, not a string special case that has to be replaced.

/// One installed SQL parser dialect.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Dialect {
    name: &'static str,
}

impl Dialect {
    /// The name accepted by `SET current_dialect` and listed by `duckdb_dialects()`.
    #[must_use]
    pub const fn name(self) -> &'static str {
        self.name
    }
}

use crate::token::{Flags, Kind, Token};

/// Every SQL parser dialect installed in this build.
pub const DIALECTS: &[Dialect] = &[Dialect { name: "duckdb" }];

/// Finds an installed dialect without regard to identifier case.
#[must_use]
pub fn dialect_named(name: &str) -> Option<Dialect> {
    DIALECTS.iter().copied().find(|dialect| dialect.name.eq_ignore_ascii_case(name))
}

/// Takes out the PostgreSQL words that the vendored grammar does not have and that change nothing
/// in rudb.
///
/// This is a stop gap until `rudb-pgparse` parses the PostgreSQL language (milestone PG4). Each
/// word leaves the token list and the source text stays the same, so the other tokens keep their
/// offsets and an error still points at the right place. One word is `UNLOGGED` in
/// `CREATE UNLOGGED TABLE` and `CREATE UNLOGGED SEQUENCE`. rudb writes every table to its log, and
/// a table that PostgreSQL does not log answers each query the same.
///
/// The other is the list of tables after the first one in `TRUNCATE a, b, c` and the options after
/// it, because the grammar takes one table and no options. The transform reads the names and the
/// options back from the text between the first table and the end of the statement, see
/// `Transform::truncated_too`. An `ONLY` before a table goes too, because no rudb table inherits
/// from another.
///
/// Two more clauses leave the tokens the same way and the transform reads them back from the text
/// of the statement, see `Transform::dropped`. One is `GENERATED ALWAYS AS IDENTITY` and
/// `GENERATED BY DEFAULT AS IDENTITY` with its sequence options, which the grammar does not have
/// on a column. The other is `OVERRIDING SYSTEM VALUE` and `OVERRIDING USER VALUE` in an `INSERT`.
pub fn postgres_tokens(query: &str, tokens: &mut Vec<Token>) {
    let word = |token: &Token, text: &str| {
        matches!(token.kind, Kind::Identifier | Kind::Keyword)
            && token.text(query).eq_ignore_ascii_case(text)
    };
    let mut at = 1;
    while at + 1 < tokens.len() {
        let next = &tokens[at + 1];
        if word(&tokens[at], "unlogged")
            && word(&tokens[at - 1], "create")
            && (word(next, "table") || word(next, "sequence"))
        {
            tokens.remove(at);
        }
        at += 1;
    }
    let mut at = 0;
    while at < tokens.len() {
        if word(&tokens[at], "truncate")
            && let Some((list, only)) = truncate_list(query, tokens, at + 1)
        {
            tokens.drain(list);
            if let Some(only) = only {
                tokens.remove(only);
            }
        }
        at += 1;
    }
    let mut at = 0;
    while at < tokens.len() {
        if let Some(end) =
            identity_clause(query, tokens, at).or_else(|| overriding(query, tokens, at))
        {
            tokens.drain(at..end);
        } else {
            at += 1;
        }
    }
}

/// The end of `GENERATED {ALWAYS | BY DEFAULT} AS IDENTITY [( options )]` when it starts at token
/// `at`. The options end at the parenthesis that closes the first one.
fn identity_clause(query: &str, tokens: &[Token], at: usize) -> Option<usize> {
    let word = |at: usize, text: &str| {
        tokens.get(at).is_some_and(|token| {
            matches!(token.kind, Kind::Identifier | Kind::Keyword)
                && token.text(query).eq_ignore_ascii_case(text)
        })
    };
    if !word(at, "generated") {
        return None;
    }
    let mut end = if word(at + 1, "always") {
        at + 2
    } else if word(at + 1, "by") && word(at + 2, "default") {
        at + 3
    } else {
        return None;
    };
    if !word(end, "as") || !word(end + 1, "identity") {
        return None;
    }
    end += 2;
    if tokens.get(end).is_some_and(|token| token.text(query) == "(") {
        let mut depth = 0usize;
        loop {
            let token = tokens.get(end)?;
            match token.text(query) {
                "(" => depth += 1,
                ")" => depth -= 1,
                _ if matches!(token.kind, Kind::Terminator | Kind::EndOfInput) => return None,
                _ => {}
            }
            end += 1;
            if depth == 0 {
                break;
            }
        }
    }
    Some(end)
}

/// The end of `OVERRIDING {SYSTEM | USER} VALUE` when it starts at token `at`.
fn overriding(query: &str, tokens: &[Token], at: usize) -> Option<usize> {
    let word = |at: usize, text: &str| {
        tokens.get(at).is_some_and(|token| {
            matches!(token.kind, Kind::Identifier | Kind::Keyword)
                && token.text(query).eq_ignore_ascii_case(text)
        })
    };
    (word(at, "overriding")
        && (word(at + 1, "system") || word(at + 1, "user"))
        && word(at + 2, "value"))
    .then_some(at + 3)
}

/// The tokens of `, b, c` and of the options in `TRUNCATE [TABLE] [ONLY] a, b, c [options]`, where
/// `from` is the token after `TRUNCATE`, and the token of the first `ONLY`. The options are
/// `RESTART IDENTITY`, `CONTINUE IDENTITY`, `CASCADE` and `RESTRICT`. `None` if the statement has
/// none of these or has any other word after its tables.
fn truncate_list(
    query: &str,
    tokens: &[Token],
    from: usize,
) -> Option<(std::ops::Range<usize>, Option<usize>)> {
    let is = |at: usize, text: &str| tokens.get(at).is_some_and(|t| t.text(query) == text);
    let word = |at: usize, text: &str| {
        tokens.get(at).is_some_and(|t| {
            matches!(t.kind, Kind::Identifier | Kind::Keyword)
                && t.text(query).eq_ignore_ascii_case(text)
        })
    };
    let name = |mut at: usize| -> Option<usize> {
        if word(at, "only") {
            at += 1;
        }
        let part = |at: usize| {
            tokens.get(at).is_some_and(|t| t.kind.is_identifier() || t.kind == Kind::Keyword)
        };
        if !part(at) {
            return None;
        }
        at += 1;
        while is(at, ".") && part(at + 1) {
            at += 2;
        }
        Some(at)
    };
    let mut at = from;
    if word(at, "table") {
        at += 1;
    }
    let only = word(at, "only").then_some(at);
    let start = name(at)?;
    at = start;
    while is(at, ",") {
        at = name(at + 1)?;
    }
    loop {
        if (word(at, "restart") || word(at, "continue")) && word(at + 1, "identity") {
            at += 2;
        } else if word(at, "cascade") || word(at, "restrict") {
            at += 1;
        } else {
            break;
        }
    }
    let end = tokens.get(at)?;
    (matches!(end.kind, Kind::Terminator | Kind::EndOfInput) && (at > start || only.is_some()))
        .then_some((start..at, only))
}

/// Takes the `ISOLATION LEVEL` clauses out of `BEGIN` and `START TRANSACTION`, which the vendored
/// grammar does not have and the pin's parser does, and marks the `BEGIN` of a transaction that
/// asked for `SERIALIZABLE` with [`Flags::SERIALIZABLE`].
///
/// The pin parses every level and runs snapshot isolation under all of them. rudb does the same for
/// the others and runs `SERIALIZABLE` serializable, which is the one place it goes past the pin
/// (`engine-v4/18-compat.md` section 18.7). As with [`postgres_tokens`], the tokens leave the list
/// and the text stays, so an error still points at the right place.
pub fn isolation_levels(query: &str, tokens: &mut Vec<Token>) {
    let word = |token: &Token, text: &str| {
        matches!(token.kind, Kind::Identifier | Kind::Keyword)
            && token.text(query).eq_ignore_ascii_case(text)
    };
    let comma = |token: &Token| token.kind == Kind::Operator && token.text(query) == ",";
    let mut at = 0;
    while at < tokens.len() {
        let starts = at == 0 || tokens[at - 1].kind == Kind::Terminator;
        if !(starts && (word(&tokens[at], "begin") || word(&tokens[at], "start"))) {
            at += 1;
            continue;
        }
        let begin = at;
        at += 1;
        if at < tokens.len() && (word(&tokens[at], "transaction") || word(&tokens[at], "work")) {
            at += 1;
        }
        // The modes, each a level or a READ ONLY or READ WRITE, with commas between them.
        loop {
            let clause = if at + 1 < tokens.len() && comma(&tokens[at]) { at + 1 } else { at };
            if !(clause + 2 < tokens.len()
                && word(&tokens[clause], "isolation")
                && word(&tokens[clause + 1], "level"))
            {
                if clause + 1 < tokens.len()
                    && word(&tokens[clause], "read")
                    && (word(&tokens[clause + 1], "only") || word(&tokens[clause + 1], "write"))
                {
                    at = clause + 2;
                    continue;
                }
                break;
            }
            let level = clause + 2;
            let words = match () {
                () if word(&tokens[level], "serializable") || word(&tokens[level], "snapshot") => 1,
                () if level + 1 < tokens.len()
                    && ((word(&tokens[level], "repeatable")
                        && word(&tokens[level + 1], "read"))
                        || (word(&tokens[level], "read")
                            && (word(&tokens[level + 1], "committed")
                                || word(&tokens[level + 1], "uncommitted")))) =>
                {
                    2
                }
                () => break,
            };
            if word(&tokens[level], "serializable") {
                tokens[begin].flags = tokens[begin].flags.with(Flags::SERIALIZABLE);
            }
            // The comma before the clause goes with it, or, for the first mode, the one after it.
            let mut end = level + words;
            if clause == at && end < tokens.len() && comma(&tokens[end]) {
                end += 1;
            }
            tokens.drain(at..end);
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{DIALECTS, dialect_named, isolation_levels, postgres_tokens};

    #[test]
    fn the_vendored_grammar_is_the_one_registered_dialect() {
        assert_eq!(DIALECTS.len(), 1);
        assert_eq!(dialect_named("DUCKDB").map(|dialect| dialect.name()), Some("duckdb"));
        assert_eq!(dialect_named("cypher"), None);
    }

    #[test]
    fn a_postgres_session_reads_create_unlogged_as_create() {
        let query = "CREATE UNLOGGED TABLE t (a INT); SELECT unlogged FROM t";
        let mut tokens = crate::tokenize(query).expect("tokens");
        let before = tokens.len();
        postgres_tokens(query, &mut tokens);
        assert_eq!(tokens.len(), before - 1);
        assert_eq!(tokens[1].text(query), "TABLE");
        assert!(tokens.iter().any(|token| token.text(query) == "unlogged"));
    }

    #[test]
    fn a_postgres_session_takes_the_list_of_a_truncate_out_of_the_tokens() {
        let texts = |query: &str| {
            let mut tokens = crate::tokenize(query).expect("tokens");
            postgres_tokens(query, &mut tokens);
            tokens.iter().map(|token| token.text(query).to_string()).collect::<Vec<_>>()
        };
        assert_eq!(
            texts("truncate table a, s.b, \"C\"; select 1"),
            ["truncate", "table", "a", ";", "select", "1", ""]
        );
        assert_eq!(texts("truncate a"), ["truncate", "a", ""]);
        assert_eq!(texts("truncate a, b cascade"), ["truncate", "a", ""]);
        assert_eq!(texts("truncate only a restart identity"), ["truncate", "a", ""]);
        assert_eq!(
            texts("TRUNCATE TABLE a CONTINUE IDENTITY RESTRICT"),
            ["TRUNCATE", "TABLE", "a", ""]
        );
        assert_eq!(texts("truncate a, b where"), ["truncate", "a", ",", "b", "where", ""]);
    }

    #[test]
    fn a_postgres_session_takes_identity_and_overriding_out_of_the_tokens() {
        let texts = |query: &str| {
            let mut tokens = crate::tokenize(query).expect("tokens");
            postgres_tokens(query, &mut tokens);
            tokens.iter().map(|token| token.text(query).to_string()).collect::<Vec<_>>()
        };
        assert_eq!(
            texts("create table t (id int generated by default as identity (start 5), v int)"),
            ["create", "table", "t", "(", "id", "int", ",", "v", "int", ")", ""]
        );
        assert_eq!(
            texts("create table t (id int generated always as identity primary key)"),
            ["create", "table", "t", "(", "id", "int", "primary", "key", ")", ""]
        );
        assert_eq!(
            texts("insert into t overriding system value values (1)"),
            ["insert", "into", "t", "values", "(", "1", ")", ""]
        );
        let generated = "create table t (a int generated always as (1))";
        assert_eq!(texts(generated).len(), crate::tokenize(generated).expect("tokens").len());
    }

    /// The words left of `query` once the levels are out, and whether each `BEGIN` asked for
    /// `SERIALIZABLE`.
    fn levels(query: &str) -> (String, Vec<bool>) {
        let mut tokens = crate::tokenize(query).expect("tokens");
        isolation_levels(query, &mut tokens);
        let words = tokens.iter().map(|token| token.text(query)).collect::<Vec<_>>();
        let serializable = tokens
            .iter()
            .filter(|token| token.text(query).eq_ignore_ascii_case("begin"))
            .map(|token| token.flags.has(super::Flags::SERIALIZABLE))
            .collect();
        (words.join(" ").trim().to_string(), serializable)
    }

    #[test]
    fn a_begin_keeps_its_read_mode_and_says_whether_it_asked_for_serializable() {
        let cases = [
            ("BEGIN TRANSACTION ISOLATION LEVEL SERIALIZABLE", "BEGIN TRANSACTION", true),
            ("begin isolation level serializable, read only", "begin read only", true),
            ("BEGIN READ WRITE, ISOLATION LEVEL SERIALIZABLE", "BEGIN READ WRITE", true),
            ("BEGIN ISOLATION LEVEL REPEATABLE READ", "BEGIN", false),
            ("BEGIN WORK ISOLATION LEVEL READ COMMITTED READ ONLY", "BEGIN WORK READ ONLY", false),
            ("BEGIN ISOLATION LEVEL READ UNCOMMITTED", "BEGIN", false),
            ("BEGIN", "BEGIN", false),
        ];
        for (query, left, serializable) in cases {
            assert_eq!(levels(query), (left.to_string(), vec![serializable]), "{query}");
        }
        let (left, _) = levels("START TRANSACTION ISOLATION LEVEL SERIALIZABLE; SELECT 1");
        assert_eq!(left, "START TRANSACTION ; SELECT 1");
        // Only at the start of a statement, and a level it does not know is left to fail.
        let query = "SELECT begin, isolation FROM t; BEGIN ISOLATION LEVEL CHAOS";
        assert_eq!(levels(query).0, query.replace(';', " ;").replace(',', " ,"));
    }
}
